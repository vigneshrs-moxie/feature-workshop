const esc = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

export function pixelText(text, { px = 2, className = '', label = null } = {}) {
  const chars = [...String(text).toUpperCase().replace(/…/g, '...')];
  let x = 0;
  let d = '';
  for (const ch of chars) {
    const glyph = G[ch] ?? G['?'];
    glyph.forEach((row, y) => {
      let i = 0;
      while (i < row.length) {
        if (row[i] !== '#') { i++; continue; }
        let run = 1;
        while (row[i + run] === '#') run++;
        d += `M${x + i} ${y}h${run}v1h-${run}z`;
        i += run;
      }
    });
    x += glyph[0].length + 1;
  }
  const w = Math.max(1, x - 1);
  const svg = `<svg class="ptext ${className}" viewBox="0 0 ${w} 7" width="${w * px}" height="${7 * px}" shape-rendering="crispEdges" aria-hidden="true" focusable="false"><path fill="currentColor" d="${d}"/></svg>`;
  const readable = label ?? text;
  return `<span class="pt"><span class="visually-hidden">${esc(readable)}</span>${svg}</span>`;
}
